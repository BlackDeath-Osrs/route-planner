"""Builds src/main/resources/com/routeplanner/sailing/docks.tsv for Route Planner.

Usage: python3 docks.py collision-map.zip mooring_points.tsv docks.tsv

The collision map keeps open water walkable but separate from the land (harbours are blocked), so
each dock is two tiles: the walkable land tile nearest the wiki's map pin (not in any water), and
the nearest water tile to that. Water is everything connected to the seed tiles below.
"""
import sys
from collision import CollisionMap

# One tile in each body of water a boat can be on, plane 0: the four open seas (as in Shortest
# Path's SeaReachabilityTest) and the channel inside Wyrmscraig Cavern.
WATER_SEEDS = [(2048, 2104), (3072, 3968), (1024, 3040), (1024, 2104), (2575, 8600)]


def ring(x, y, r):
    return sorted((abs(dx) + abs(dy), x + dx, y + dy) for dx in range(-r, r + 1) for dy in range(-r, r + 1))


def main(map_path, pins_path, out_path):
    m = CollisionMap(map_path)
    water = set()
    for seed in WATER_SEEDS:
        if seed not in water:
            body = m.flood(seed)
            print('water from', seed, len(body), file=sys.stderr)
            water |= body
    rows, failed = [], []
    for line in open(pins_path):
        if line.startswith('#') or not line.strip():
            continue
        name, level, x, y, port = line.rstrip('\n').split('\t')
        x, y = int(x), int(y)
        land = next(((a, b) for _, a, b in ring(x, y, 8) if m.walkable(a, b) and (a, b) not in water), None)
        sea = land and next(((a, b) for _, a, b in ring(land[0], land[1], 12) if (a, b) in water), None)
        if not land or not sea:
            failed.append(name)
            continue
        gap = abs(sea[0] - land[0]) + abs(sea[1] - land[1])
        print(f'{name:24} land={land} sea={sea} gap={gap}' + ('  <-- check' if gap > 5 else ''), file=sys.stderr)
        rows.append(f'{name}\t{level}\t{land[0]} {land[1]} 0\t{sea[0]} {sea[1]} 0\t{port}')
    with open(out_path, 'w') as out:
        out.write('# Sailing mooring points. Generated by scripts/sailing/docks.py from the OSRS wiki\'s Mooring point\n')
        out.write('# list (map pins) and the bundled collision map: Dock is the walkable land tile at the gangplank,\n')
        out.write('# Mooring the nearest water tile, which the collision map keeps separate from the land. Port id is the\n')
        out.write("# game's dock id, the value of a boat's SAILING_BOAT_n_PORT varbit while it's moored there.\n")
        out.write('# Name\tSailing level\tDock (land)\tMooring (sea)\tPort id\n')
        out.write('\n'.join(rows) + '\n')
    print('failed:', failed, file=sys.stderr)


if __name__ == '__main__':
    main(*sys.argv[1:4])
